# Digit-wheel spin boxes
# ---------------------------------------------------------------------
# Hovering the mouse over a particular digit of the displayed number and
# scrolling the wheel steps that digit (XDI-style). E.g. with the
# cursor on the tenths digit, one wheel notch changes the value by 0.1;
# on the hundreds digit, by 100. When the cursor is not over any digit
# (over the suffix/prefix, or the spinner is not focused under the
# mouse), behaviour falls back to the spin box's pre-set singleStep.
#
# The classes are aliased onto QtWidgets.QDoubleSpinBox and
# QtWidgets.QSpinBox at module import time so every spinbox created by
# the rest of EXODUS_GUI_ui.py (and by EXODUS_main.py — which imports
# QtWidgets from PyQt5 directly, but resolves QtWidgets.QDoubleSpinBox
# at call time) automatically inherits the new wheel behaviour.
# =====================================================================

def _digit_step_for_position(spinbox, mouseX):
    """Return the step size that corresponds to the digit under
    ``mouseX`` (in widget coordinates) in ``spinbox``'s displayed text.
    Returns ``None`` if the cursor is not over a digit (e.g. it's on
    the spinner arrows, the suffix, the decimal separator, or outside
    the line-edit's text area).
    """
    line_edit = spinbox.lineEdit()
    if line_edit is None:
        return None

    # Map the mouse x from the spinbox to the embedded line-edit.
    le_x = mouseX - line_edit.x()
    if le_x < 0 or le_x > line_edit.width():
        return None

    text = line_edit.text()
    if not text:
        return None

    # Trim prefix/suffix so we only consider the numeric portion.
    prefix = spinbox.prefix() or ""
    suffix = spinbox.suffix() or ""
    num_start = len(prefix)
    num_end = len(text) - len(suffix)
    if num_start >= num_end:
        return None

    # Find which character index the mouse sits over via the line edit's
    # own cursor mapping. cursorPositionAt() returns the position to
    # the LEFT of the character at that x, so we treat that as "the
    # character to the right of the cursor" — which is the digit the
    # user is visually pointing at.
    cursor_pos = line_edit.cursorPositionAt(QtCore.QPoint(le_x, line_edit.height() // 2))
    if cursor_pos >= len(text):
        cursor_pos = len(text) - 1
    if cursor_pos < num_start or cursor_pos >= num_end:
        return None

    char = text[cursor_pos]
    if not char.isdigit():
        return None

    numeric_text = text[num_start:num_end]
    # Locate decimal point (locale-aware: accept both '.' and ',')
    dot_index = -1
    for sep in ('.', ','):
        idx = numeric_text.find(sep)
        if idx != -1:
            dot_index = idx
            break

    # Local index of the hovered character inside the numeric substring
    local_idx = cursor_pos - num_start

    if dot_index == -1:
        # Integer-only: rightmost digit is units, next is tens, etc.
        # numeric_text may contain a leading sign; skip it for power.
        digits_only = numeric_text.lstrip('+-')
        sign_offset = len(numeric_text) - len(digits_only)
        digit_pos_from_right = (len(numeric_text) - 1) - local_idx
        if local_idx < sign_offset:
            return None
        power = digit_pos_from_right
    else:
        if local_idx < dot_index:
            # Integer side: power = number of digits between this digit
            # and the decimal point (exclusive of the dot).
            power = (dot_index - 1) - local_idx
        elif local_idx == dot_index:
            return None  # cursor on the decimal point itself
        else:
            # Fractional side: power = -(distance after the dot)
            power = -(local_idx - dot_index)

    return 10.0 ** power


class DigitWheelDoubleSpinBox(_OriginalQDoubleSpinBox):
    """QDoubleSpinBox whose wheel step depends on which digit the
    mouse hovers over. See module-level docstring."""

    def wheelEvent(self, event):
        # angleDelta().y() is +120 per notch up (typical mouse wheel).
        delta = event.angleDelta().y()
        if delta == 0:
            event.ignore()
            return
        notches = delta / 120.0

        step = _digit_step_for_position(self, event.x())
        if step is None:
            # Fallback: pre-set singleStep (default behaviour)
            super().wheelEvent(event)
            return

        new_value = self.value() + notches * step
        # Clamp to spinbox limits.
        new_value = max(self.minimum(), min(self.maximum(), new_value))
        self.setValue(new_value)
        event.accept()


class DigitWheelSpinBox(_OriginalQSpinBox):
    """QSpinBox variant of DigitWheelDoubleSpinBox (integer steps).
    For fractional digit positions the step rounds up to 1."""

    def wheelEvent(self, event):
        delta = event.angleDelta().y()
        if delta == 0:
            event.ignore()
            return
        notches = delta // 120 if delta > 0 else -((-delta) // 120)
        if notches == 0:
            notches = 1 if delta > 0 else -1

        step = _digit_step_for_position(self, event.x())
        if step is None:
            super().wheelEvent(event)
            return

        # Integer spin box: round step to nearest integer >= 1.
        int_step = max(1, int(round(step)))
        new_value = self.value() + notches * int_step
        new_value = max(self.minimum(), min(self.maximum(), new_value))
        self.setValue(new_value)
        event.accept()



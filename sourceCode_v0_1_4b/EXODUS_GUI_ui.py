    @staticmethod
    def _remove_trailing_spacer(layout):
        """Remove the last item of `layout` if it is a spacer, so spare
        height goes to the real content instead of empty space."""
        n = layout.count()
        if n and layout.itemAt(n - 1).spacerItem() is not None:
            layout.takeAt(n - 1)

    def _scroll_pane(self, panel, name):
        """Wrap a control panel in a frameless QScrollArea so the splitter
        can shrink it below its natural height (it scrolls instead).
        The minimum WIDTH is pinned to the panel's own, so the left column
        never gets narrower than its contents (no sideways scrolling)."""
        sa = QtWidgets.QScrollArea(self.centralwidget)
        sa.setObjectName(name)
        sa.setWidgetResizable(True)
        sa.setFrameShape(QtWidgets.QFrame.NoFrame)
        sa.setHorizontalScrollBarPolicy(QtCore.Qt.ScrollBarAlwaysOff)
        sa.setWidget(panel)
        sb_w = sa.verticalScrollBar().sizeHint().width()
        sa.setMinimumWidth(panel.minimumSizeHint().width() + sb_w)
        sa.setMinimumHeight(60)
        return sa

    def _build_resizable_layout(self):
        """Re-arrange the three fixed-height rows into two columns of
        splitters so every panel can be resized vertically.

        The .ui file defines three rows:
            frame_12 : [groupBox_3 (Data)          | frame_19 (Raw pattern)]
            frame_17 : [frame_16 (BG + JCPDS)      | frame_18 (Pattern)    ]
            frame_13 : [groupBox_4 (2D Plot/Fits)  | frame_20 (2D plot)    ]
        Every row is as tall as its taller half, so nothing could be
        resized independently - the left-hand controls set a hard minimum
        height per row, which is why a splitter dropped straight into
        verticalLayout_9 can't work.

        After:
            splitter_main (horizontal)
              splitter_controls (vertical):  Data | BG Subtraction |
                                             JCPDS files | 2D Plot and Fits
                  (each in a scroll area, so it can shrink and scroll)
              splitter_plots (vertical):     Raw | Pattern | 2D plot
        All widget names are unchanged, so EXODUS_main needs no changes.
        """
        # 1. Detach the blocks from their row layouts
        self.horizontalLayout_11.removeWidget(self.groupBox_3)
        self.horizontalLayout_11.removeWidget(self.frame_19)
        self.verticalLayout_5.removeWidget(self.groupBox_5)
        self.verticalLayout_5.removeWidget(self.groupBox_7)
        self.horizontalLayout_14.removeWidget(self.frame_16)
        self.horizontalLayout_14.removeWidget(self.frame_18)
        self.horizontalLayout_13.removeWidget(self.groupBox_4)
        self.horizontalLayout_13.removeWidget(self.frame_20)

        # 2. Retire the (now empty) containers
        for w in (self.frame_12, self.frame_17, self.frame_13, self.frame_23):
            self.verticalLayout_9.removeWidget(w)
            w.hide()
        self.frame_16.hide()

        # 3. Spare height should go to the JCPDS table and the
        #    pressure-guess tabs, not to the trailing spacers.
        self._remove_trailing_spacer(self.verticalLayout_2)   # JCPDS files
        self._remove_trailing_spacer(self.verticalLayout_4)   # 2D Plot and Fits

        # Splitter handles: use the plain Fusion handle (small grip dash),
        # the same as in the pop-up windows. The broad grey/green styled
        # handles are switched off below (kept commented for reference).
        # handle_qss = ("QSplitter::handle { background-color: rgb(80, 80, 80); } "
        #               "QSplitter::handle:hover { background-color: rgb(46, 204, 113); }")

        # 4. Left column: vertical splitter with the four control panels
        self.splitter_controls = QtWidgets.QSplitter(QtCore.Qt.Vertical, self.centralwidget)
        self.splitter_controls.setObjectName("splitter_controls")
        self.splitter_controls.setChildrenCollapsible(False)
        # self.splitter_controls.setHandleWidth(7)
        self._control_panels = (self.groupBox_3, self.groupBox_5,
                                self.groupBox_7, self.groupBox_4)
        names = ("scroll_data", "scroll_bg", "scroll_jcpds", "scroll_fits")
        for panel, nm in zip(self._control_panels, names):
            self.splitter_controls.addWidget(self._scroll_pane(panel, nm))
        # Panes that should absorb spare height (file list, JCPDS table)
        self._controls_grow = (0, 2)
        for i in range(4):
            self.splitter_controls.setStretchFactor(i, 1 if i in self._controls_grow else 0)
        # self.splitter_controls.setStyleSheet(handle_qss)
        self.leftColumn = self.splitter_controls      # kept for older code

        # 5. Right column: vertical splitter with the three plot panels
        self.splitter_plots = QtWidgets.QSplitter(QtCore.Qt.Vertical, self.centralwidget)
        self.splitter_plots.setObjectName("splitter_plots")
        self.splitter_plots.setChildrenCollapsible(False)
        # self.splitter_plots.setHandleWidth(7)
        for w in (self.frame_19, self.frame_18, self.frame_20):
            # Plots must be allowed to shrink - otherwise the splitter
            # handle refuses to move (pyqtgraph's size hints are large).
            w.setMinimumHeight(90)
            w.setSizePolicy(QtWidgets.QSizePolicy.Expanding,
                            QtWidgets.QSizePolicy.Ignored)
            self.splitter_plots.addWidget(w)
        self.splitter_plots.setStretchFactor(0, 2)
        self.splitter_plots.setStretchFactor(1, 3)
        self.splitter_plots.setStretchFactor(2, 3)
        # self.splitter_plots.setStyleSheet(handle_qss)

        # 6. Horizontal splitter: [controls | plots]
        self.splitter_main = QtWidgets.QSplitter(QtCore.Qt.Horizontal, self.centralwidget)
        self.splitter_main.setObjectName("splitter_main")
        self.splitter_main.setChildrenCollapsible(False)
        # self.splitter_main.setHandleWidth(7)
        self.splitter_main.addWidget(self.splitter_controls)
        self.splitter_main.addWidget(self.splitter_plots)
        self.splitter_main.setStretchFactor(0, 0)
        self.splitter_main.setStretchFactor(1, 1)
        # self.splitter_main.setStyleSheet(handle_qss)

        self.verticalLayout_9.addWidget(self.splitter_main)

    def equalise_broadening_rows(self):
        """Give the four rows of the peak-broadening grid the same height.

        Row stretch only shares out the EXTRA space, on top of each row's
        natural height. Rows 1-3 hold a spin box, which is taller than the
        check box of row 0 on most styles, so row 0 would end up shorter
        (smaller gap Caglioti -> U than U -> V). A common minimum height
        (= tallest widget) makes the rows equal. Called again by
        MainWindow.showEvent, after the style sheet has set the final sizes.
        """
        rowHeight = max(max(wdg.sizeHint().height(),
                            wdg.minimumSizeHint().height(),
                            wdg.minimumHeight()) for wdg in (
            self.checkBox_fixSigma_2, self.checkBox, self.checkBox_2,
            self.checkBox_3, self.checkBox_4_Caglioti,
            self.doubleSpinBox_5_CagliotiU, self.doubleSpinBox_2_CagliotiV,
            self.doubleSpinBox_4__CagliotiW))
        for row in range(4):
            self.gridLayout_41.setRowMinimumHeight(row, rowHeight)

